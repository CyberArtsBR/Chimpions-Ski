import path from 'node:path';
import {mkdir,readFile,stat,writeFile} from 'node:fs/promises';
import {START_CROWD_COUNT,chooseCrowdSources,crowdSourceAssetPublicPath} from '../src/crowdManifest.js';

const MiB=1024*1024;
const DEFAULT_CRITICAL_COUNT=10;
const BUDGETS=Object.freeze({
  individualBytes:2.25*MiB,
  criticalBytes:16*MiB,
  fullBytes:90*MiB
});

function parseArgs(argv){
  const options={
    catalog:'public/avatars.json',
    root:'.',
    deepAudit:'docs/avatar-asset-audit.json',
    json:'',
    markdown:'',
    strict:false,
    sourceSha:''
  };
  for(let i=2;i<argv.length;i++){
    const arg=argv[i];
    const next=()=>argv[++i];
    if(arg==='--catalog')options.catalog=next();
    else if(arg==='--root')options.root=next();
    else if(arg==='--deep-audit')options.deepAudit=next();
    else if(arg==='--json')options.json=next();
    else if(arg==='--markdown')options.markdown=next();
    else if(arg==='--source-sha')options.sourceSha=next();
    else if(arg==='--strict')options.strict=true;
    else if(arg==='--help'){
      console.log('Usage: node scripts/audit-crowd-assets.mjs [--strict] [--json FILE] [--markdown FILE] [--source-sha SHA]');
      process.exit(0);
    }else throw new Error('Unknown argument: '+arg);
  }
  return options;
}

function mib(bytes){return Number((bytes/MiB).toFixed(3));}
function basenameFromUrl(url){return path.basename(decodeURIComponent(String(url||'')));}

async function readOptionalJson(file){
  try{return JSON.parse(await readFile(file,'utf8'));}
  catch{return null;}
}

function makeMarkdown(report){
  const lines=[
    '# Chimpions Ski production crowd asset budget',
    '',
    report.sourceSha?`Source baseline: \`${report.sourceSha}\``:'Source baseline: not supplied',
    '',
    'This report is generated by `scripts/audit-crowd-assets.mjs`. Source GLBs are read-only; the audit never overwrites master assets.',
    '',
    '## Budget summary',
    '',
    `- Production spectators: **${report.summary.selectedCount}/${START_CROWD_COUNT}**`,
    `- Start-critical unique GLBs: **${report.summary.criticalCount}**`,
    `- Start-critical bytes: **${report.summary.criticalMiB} MiB** / ${mib(BUDGETS.criticalBytes)} MiB budget`,
    `- Full 50-GLB pool: **${report.summary.totalMiB} MiB** / ${mib(BUDGETS.fullBytes)} MiB budget`,
    `- Largest selected GLB: **${report.summary.largestMiB} MiB** / ${mib(BUDGETS.individualBytes)} MiB budget`,
    `- Duplicate source keys: **${report.summary.duplicateSourceKeys}**`,
    `- Missing files: **${report.summary.missingFiles}**`,
    '',
    '## Selected production crowd',
    '',
    '| # | Tier | Chimpion | MiB | Textures > 2048 | Vertices |',
    '| ---: | --- | --- | ---: | ---: | ---: |'
  ];
  for(const item of report.assets){
    lines.push(`| ${item.index+1} | ${item.classification} | ${item.name} | ${item.mib} | ${item.oversizedTextureCount??'n/a'} | ${item.vertexCount??'n/a'} |`);
  }
  lines.push('','## Findings','');
  if(report.errors.length)for(const error of report.errors)lines.push(`- ERROR: ${error}`);
  if(report.warnings.length)for(const warning of report.warnings)lines.push(`- WARN: ${warning}`);
  if(!report.errors.length&&!report.warnings.length)lines.push('- No budget or metadata warnings.');
  lines.push('','## Runtime contract','',
    '- The first 10 ordered assets are the start-critical near subset.',
    '- The remaining unique GLBs are progressive/background work.',
    '- Runtime template caching may share immutable geometry/material/texture resources, but each SkinnedMesh actor keeps independent Skeleton state.',
    '- Generated browser LODs, if added later, must live separately from `public/model/characters` source assets.'
  );
  return lines.join('\n');
}

async function main(){
  const options=parseArgs(process.argv);
  const catalogPath=path.resolve(options.root,options.catalog);
  const catalog=JSON.parse(await readFile(catalogPath,'utf8'));
  const selected=chooseCrowdSources(catalog,START_CROWD_COUNT);
  const deepAudit=await readOptionalJson(path.resolve(options.root,options.deepAudit));
  const deepByName=new Map((deepAudit?.models||[]).map(model=>[model.filename,model]));

  const assets=[];
  const errors=[];
  const warnings=[];
  const seenSourceKeys=new Set();
  let duplicateSourceKeys=0;

  for(let index=0;index<selected.length;index++){
    const entry=selected[index];
    const sourceKey=String(entry.id||entry.url||'');
    if(seenSourceKeys.has(sourceKey))duplicateSourceKeys++;
    seenSourceKeys.add(sourceKey);

    const relative=crowdSourceAssetPublicPath(entry);
    const absolute=path.resolve(options.root,relative);
    let bytes=0,missing=false;
    try{bytes=(await stat(absolute)).size;}
    catch{missing=true;errors.push(`Missing crowd asset: ${relative}`);}

    const filename=basenameFromUrl(entry.url);
    const deep=deepByName.get(filename);
    const item={
      index,
      id:String(entry.id||''),
      name:entry.name||filename,
      url:entry.url,
      path:relative.replace(/\\/g,'/'),
      classification:index<DEFAULT_CRITICAL_COUNT?'start-critical-near':'progressive-background',
      bytes,
      mib:mib(bytes),
      missing,
      textureCount:deep?.textureCount??null,
      oversizedTextureCount:deep?.oversizedTextures?.length??null,
      vertexCount:deep?.vertexCount??null,
      meshCount:deep?.meshCount??null,
      primitiveCount:deep?.primitiveCount??null,
      animationCount:deep?.animationCount??null,
      skinCount:deep?.skinCount??null,
      compression:deep?.compression??null
    };
    if(bytes>BUDGETS.individualBytes)errors.push(`${item.name} is ${item.mib} MiB, above the ${mib(BUDGETS.individualBytes)} MiB crowd-asset budget.`);
    if((item.oversizedTextureCount||0)>0)warnings.push(`${item.name} contains ${item.oversizedTextureCount} texture(s) above 2048px in the deep avatar audit.`);
    if((item.animationCount||0)>0)warnings.push(`${item.name} contains ${item.animationCount} animation(s); crowd runtime does not require animation clips.`);
    assets.push(item);
  }

  if(selected.length!==START_CROWD_COUNT)errors.push(`Expected ${START_CROWD_COUNT} unique production crowd sources, found ${selected.length}.`);
  if(duplicateSourceKeys)errors.push(`Production crowd manifest contains ${duplicateSourceKeys} duplicate source key(s).`);

  const totalBytes=assets.reduce((sum,item)=>sum+item.bytes,0);
  const criticalBytes=assets.slice(0,DEFAULT_CRITICAL_COUNT).reduce((sum,item)=>sum+item.bytes,0);
  const largestBytes=Math.max(0,...assets.map(item=>item.bytes));
  if(totalBytes>BUDGETS.fullBytes)errors.push(`Full crowd is ${mib(totalBytes)} MiB, above ${mib(BUDGETS.fullBytes)} MiB budget.`);
  if(criticalBytes>BUDGETS.criticalBytes)errors.push(`Start-critical crowd is ${mib(criticalBytes)} MiB, above ${mib(BUDGETS.criticalBytes)} MiB budget.`);
  if(!deepAudit)warnings.push(`Deep avatar audit not found/readable at ${options.deepAudit}; texture/geometry metadata is unavailable.`);

  const report={
    schemaVersion:1,
    sourceSha:options.sourceSha,
    generatedAt:new Date().toISOString(),
    budgets:{
      individualMiB:mib(BUDGETS.individualBytes),
      criticalMiB:mib(BUDGETS.criticalBytes),
      fullMiB:mib(BUDGETS.fullBytes)
    },
    summary:{
      selectedCount:selected.length,
      criticalCount:Math.min(DEFAULT_CRITICAL_COUNT,selected.length),
      totalBytes,
      totalMiB:mib(totalBytes),
      criticalBytes,
      criticalMiB:mib(criticalBytes),
      largestBytes,
      largestMiB:mib(largestBytes),
      duplicateSourceKeys,
      missingFiles:assets.filter(item=>item.missing).length,
      deepAuditAvailable:!!deepAudit
    },
    warnings,
    errors,
    assets
  };

  if(options.json){
    const output=path.resolve(options.root,options.json);
    await mkdir(path.dirname(output),{recursive:true});
    await writeFile(output,JSON.stringify(report,null,2)+'\n');
  }
  if(options.markdown){
    const output=path.resolve(options.root,options.markdown);
    await mkdir(path.dirname(output),{recursive:true});
    await writeFile(output,makeMarkdown(report)+'\n');
  }

  console.log(JSON.stringify({
    selectedCount:report.summary.selectedCount,
    criticalMiB:report.summary.criticalMiB,
    totalMiB:report.summary.totalMiB,
    largestMiB:report.summary.largestMiB,
    warnings:warnings.length,
    errors:errors.length
  }));
  if(options.strict&&errors.length)process.exitCode=1;
}

await main();
